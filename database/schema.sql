-- ---------- ฟังก์ชันกลาง: อัปเดต updated_at อัตโนมัติ ----------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------- profiles: ชื่อที่แสดงของผู้ใช้ (1:1 กับ auth.users) ----------
-- อีเมลกับรหัสผ่านอยู่ใน auth.users ของ Supabase Auth (hash แล้ว) ไม่เก็บซ้ำที่นี่
create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  name        text not null check (char_length(btrim(name)) between 1 and 100),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- ---------- pets: โพสต์หาบ้าน ----------
create table if not exists public.pets (
  id           integer generated by default as identity primary key,
  owner_id     uuid not null references public.profiles (id) on delete cascade,
  name         text not null check (char_length(btrim(name)) between 1 and 100),
  species      text not null check (species in ('DOG', 'CAT', 'OTHER')),
  breed        text not null default '' check (char_length(breed) <= 100),
  age_months   integer not null check (age_months between 0 and 300),
  sex          text not null check (sex in ('MALE', 'FEMALE')),
  province     text not null check (char_length(btrim(province)) between 1 and 100),
  image_url    text not null default '' check (char_length(image_url) <= 2048),
  description  text not null check (char_length(btrim(description)) between 1 and 5000),
  vaccinated   boolean not null default false,
  sterilized   boolean not null default false,
  urgent       boolean not null default false,
  status       text not null default 'AVAILABLE' check (status in ('AVAILABLE', 'PENDING', 'ADOPTED')),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists pets_created_at_idx on public.pets (created_at desc);
create index if not exists pets_owner_id_idx   on public.pets (owner_id);
create index if not exists pets_species_idx    on public.pets (species);
create index if not exists pets_province_idx   on public.pets (province);
create index if not exists pets_urgent_idx     on public.pets (created_at desc) where urgent;

-- ---------- favorites: รายการโปรด (1 คนกด ♡ น้อง 1 ตัวได้ครั้งเดียว) ----------
create table if not exists public.favorites (
  user_id     uuid not null references public.profiles (id) on delete cascade,
  pet_id      integer not null references public.pets (id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (user_id, pet_id)
);

create index if not exists favorites_pet_id_idx on public.favorites (pet_id);

-- ---------- adoption_requests: คำขอรับเลี้ยง ----------
create table if not exists public.adoption_requests (
  id          integer generated by default as identity primary key,
  pet_id      integer not null references public.pets (id) on delete cascade,
  user_id     uuid not null references public.profiles (id) on delete cascade,
  phone       text not null check (phone ~ '^0[0-9]{8,9}$'),
  housing     text not null check (housing in ('HOUSE', 'CONDO', 'DORM')),
  message     text not null check (char_length(btrim(message)) between 1 and 2000),
  status      text not null default 'PENDING' check (status in ('PENDING', 'APPROVED', 'REJECTED')),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  unique (user_id, pet_id)
);

create index if not exists adoption_requests_pet_id_idx on public.adoption_requests (pet_id);
-- อนุมัติได้คนเดียวต่อน้อง 1 ตัว (กันกดอนุมัติพร้อมกันสองคน)
create unique index if not exists adoption_requests_one_approved_per_pet
  on public.adoption_requests (pet_id) where status = 'APPROVED';

-- ---------- triggers ----------
drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at before update on public.profiles
  for each row execute function public.set_updated_at();

drop trigger if exists pets_set_updated_at on public.pets;
create trigger pets_set_updated_at before update on public.pets
  for each row execute function public.set_updated_at();

drop trigger if exists adoption_requests_set_updated_at on public.adoption_requests;
create trigger adoption_requests_set_updated_at before update on public.adoption_requests
  for each row execute function public.set_updated_at();

-- สมัครผ่าน Supabase Auth แล้วสร้าง profile ให้อัตโนมัติ (ชื่อจาก user_metadata.name)
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, name)
  values (
    new.id,
    -- ไม่มีชื่อและไม่มีอีเมล (เช่นสมัครด้วยเบอร์โทร) ต้องยังสร้างได้ ไม่งั้นการสมัครทั้งก้อนจะล้ม
    left(coalesce(
      nullif(btrim(new.raw_user_meta_data ->> 'name'), ''),
      nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
      'ผู้ใช้'
    ), 100)
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

-- เรียกได้จาก trigger เท่านั้น ไม่เปิดให้ยิงผ่าน /rest/v1/rpc
revoke execute on function public.handle_new_user() from public, anon, authenticated;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------- Row Level Security ----------
-- Backend ต่อด้วย role postgres (Prisma) จึงไม่ติด RLS และตรวจสิทธิ์เองในโค้ด
-- RLS นี้กันกรณีมีคนใช้ anon key ยิงตรงเข้า PostgREST: อ่านข้อมูลสาธารณะได้ แก้ได้เฉพาะของตัวเอง
-- สิทธิ์ระดับตารางให้ชัด (ไม่พึ่งค่าเริ่มต้นของโปรเจกต์) แล้วให้ RLS ตัดสินระดับแถว
grant select on public.profiles, public.pets to anon, authenticated;
grant select, insert, update, delete on public.profiles, public.pets, public.favorites, public.adoption_requests to authenticated;
grant usage on all sequences in schema public to authenticated;

alter table public.profiles          enable row level security;
alter table public.pets              enable row level security;
alter table public.favorites         enable row level security;
alter table public.adoption_requests enable row level security;

-- profiles: ชื่อผู้โพสต์เป็นข้อมูลสาธารณะ แก้ได้เฉพาะของตัวเอง
drop policy if exists "profiles: read all" on public.profiles;
create policy "profiles: read all" on public.profiles
  for select to anon, authenticated using (true);

drop policy if exists "profiles: update own" on public.profiles;
create policy "profiles: update own" on public.profiles
  for update to authenticated
  using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

-- pets: ทุกคนอ่านได้ เจ้าของสร้าง/แก้/ลบได้
drop policy if exists "pets: read all" on public.pets;
create policy "pets: read all" on public.pets
  for select to anon, authenticated using (true);

drop policy if exists "pets: insert own" on public.pets;
create policy "pets: insert own" on public.pets
  for insert to authenticated with check ((select auth.uid()) = owner_id);

drop policy if exists "pets: update own" on public.pets;
create policy "pets: update own" on public.pets
  for update to authenticated
  using ((select auth.uid()) = owner_id) with check ((select auth.uid()) = owner_id);

drop policy if exists "pets: delete own" on public.pets;
create policy "pets: delete own" on public.pets
  for delete to authenticated using ((select auth.uid()) = owner_id);

-- favorites: เห็นและจัดการได้เฉพาะของตัวเอง
drop policy if exists "favorites: own" on public.favorites;
create policy "favorites: own" on public.favorites
  for all to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

-- adoption_requests: ผู้ยื่นเห็นของตัวเอง · เจ้าของน้องเห็นคำขอของน้องตัวเอง (มีเบอร์โทร ห้ามเปิดสาธารณะ)
drop policy if exists "adoptions: read own or pet owner" on public.adoption_requests;
create policy "adoptions: read own or pet owner" on public.adoption_requests
  for select to authenticated using (
    (select auth.uid()) = user_id
    or exists (select 1 from public.pets p where p.id = pet_id and p.owner_id = (select auth.uid()))
  );

drop policy if exists "adoptions: insert own" on public.adoption_requests;
create policy "adoptions: insert own" on public.adoption_requests
  for insert to authenticated with check (
    (select auth.uid()) = user_id
    and status = 'PENDING'
    -- กฎเดียวกับ Backend: ห้ามขอน้องของตัวเอง และน้องที่ได้บ้านแล้ว
    and exists (
      select 1 from public.pets p
      where p.id = pet_id and p.owner_id <> (select auth.uid()) and p.status <> 'ADOPTED'
    )
  );

drop policy if exists "adoptions: pet owner reviews" on public.adoption_requests;
create policy "adoptions: pet owner reviews" on public.adoption_requests
  for update to authenticated
  using (exists (select 1 from public.pets p where p.id = pet_id and p.owner_id = (select auth.uid())))
  with check (exists (select 1 from public.pets p where p.id = pet_id and p.owner_id = (select auth.uid())));

drop policy if exists "adoptions: cancel own pending" on public.adoption_requests;
create policy "adoptions: cancel own pending" on public.adoption_requests
  for delete to authenticated using ((select auth.uid()) = user_id and status = 'PENDING');

